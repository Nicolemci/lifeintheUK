import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const config = JSON.parse(readFileSync(join(root, "src/config/seo-routes.json"), "utf8"));
const siteUrl = (process.env.VITE_SITE_URL || config.defaultSiteUrl).replace(/\/+$/, "");
const publicDir = join(root, "public");
const today = new Date().toISOString().slice(0, 10);

mkdirSync(publicDir, { recursive: true });

const sitemapEntries = config.sitemapRoutes
  .map((route) => {
    const loc = route.path === "/" ? `${siteUrl}/` : `${siteUrl}${route.path}`;
    return `  <url>
    <loc>${loc}</loc>
    <lastmod>${today}</lastmod>
    <changefreq>${route.changefreq}</changefreq>
    <priority>${route.priority}</priority>
  </url>`;
  })
  .join("\n");

const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${sitemapEntries}
</urlset>
`;

const disallowLines = config.robotsDisallow.map((path) => `Disallow: ${path}`).join("\n");

const robots = `# Generated by scripts/generate-seo-files.mjs — do not edit by hand.
User-agent: *
Allow: /
${disallowLines}

Sitemap: ${siteUrl}/sitemap.xml
`;

writeFileSync(join(publicDir, "sitemap.xml"), sitemap);
writeFileSync(join(publicDir, "robots.txt"), robots);

console.log(`Generated sitemap.xml (${config.sitemapRoutes.length} URLs) and robots.txt for ${siteUrl}`);
